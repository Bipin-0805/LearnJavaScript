
function add(a,b){
    return a+b;
}

function sub(a,b){
    return a-b;
}

function mul(a,b){
    return a*b;
}

function div(a,b){
    return a/b;
}

function rem(a,b){
    return a%b;
}

function exponential(a,b){
    return a**b;
}


console.log(add(10,3));
console.log(sub(10,3));
console.log(mul(10,3));
console.log(div(10,3));
console.log(rem(10,3));
console.log(exponential(2,3));
